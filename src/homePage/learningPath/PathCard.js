import "./PathCard.css";

function PathCard({ path }) {
  const { image, title, text, time } = path;
  /* массив цветов для текста в span каждой карточки */
  const colorText = ["#8FA0FF", "#FF9A82", "#6EE7B7", "#FFD766"]; 
  return (
    <div className="pathCard">
      <div className="textCard">
      <img src={image} alt={title} />
      <h3>{title}</h3>
      <p>{text}</p>
      <span
        style={{
          /* ????????????????????????????????????????????????????????????????????????? */
          color: colorText[Math.floor(Math.random() * colorText.length)],
        }}
      >
        {time}
      </span>
      </div>
    </div>
  );
}

export default PathCard;
