def item(q: str, a, exp: str) -> dict:
    return {"question": q, "answer": str(a), "explanation": exp}


def unique(rows: list[dict], n: int, extra: list[dict] | None = None) -> list[dict]:
    seen: set[str] = set()
    out: list[dict] = []
    for r in rows + (extra or []):
        if r["question"] in seen:
            continue
        seen.add(r["question"])
        out.append(r)
        if len(out) >= n:
            break
    if len(out) != n:
        raise SystemExit(f"Собрано {len(out)}, нужно {n}")
    return out


