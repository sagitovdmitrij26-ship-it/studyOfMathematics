    formula = formula_from_question(question)
    lines = wrap_text(formula, 28)
    font_size = 28 if any(len(line) > 24 for line in lines) else 36
    start_y = 268 - ((len(lines) - 1) * (font_size + 10)) / 2
    tspan = []
    for i, line in enumerate(lines):
        dy = 0 if i == 0 else font_size + 10
