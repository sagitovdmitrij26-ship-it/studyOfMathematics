def gcd(a: int, b: int) -> int:
    a, b = abs(a), abs(b)
    while b:
        a, b = b, a % b
    return a or 1


def frac(n: int, d: int) -> str:
    g = gcd(n, d)
    n, d = n // g, d // g
    if d < 0:
        n, d = -n, -d
    if d == 1:
        return str(n)
    return f"{n}/{d}"


def dec(value: float) -> str:
    if abs(value - round(value)) < 1e-9:
        return str(int(round(value)))
    text = f"{value:.2f}".rstrip("0").rstrip(".")
    return text.replace(".", ",")


def item(question: str, answer, explanation: str) -> dict:
    if isinstance(answer, float):
        answer = dec(answer)
    else:
        answer = str(answer)
    return {
        "question": question,
        "answer": answer,
        "explanation": explanation,
    }


