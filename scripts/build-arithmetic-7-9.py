def sql_escape(value: str) -> str:
    return str(value).replace("'", "''")


def write_pack(klass: str, level: str, rows: list[dict]) -> None:
    expected = LEVELS[level][4]
    if len(rows) != expected:
        raise SystemExit(f"{klass} {level}: {len(rows)} задач, нужно {expected}")
    prefix = {"7 класс": "ar7", "8 класс": "ar8", "9 класс": "ar9"}[klass]
    letter = LEVELS[level][0]
    slug = {"Базовый": "basic", "Средний": "medium", "Высокий": "high"}[level]
    grade = klass[0]
    csv_name = f"arithmetic-{grade}-{slug}.csv"
    sql_name = f"insert-arithmetic-{grade}-{slug}.sql"

    csv_rows = []
    sql_values = []
    for i, row in enumerate(rows, start=1):
        num = f"{i:02d}"
        filename = f"{prefix}-{letter}-{num}.svg"
        image = f"/tasks/{filename}"
        answer = row["answer"]
        if isinstance(answer, float):
            answer = dec(answer)
        csv_rows.append(
            {
                "subject": "arithmetic",
                "class_name": klass,
                "level": level,
                "question": row["question"],
                "answer": answer,
                "image": image,
                "explanation_of_the_answer": row["explanation"],
            }
        )
        (TASKS / filename).write_text(
            make_svg(row["question"], level, klass, i, len(rows)),
            encoding="utf-8",
        )
        sql_values.append(
            "  ('arithmetic', '{klass}', '{level}', '{q}', '{a}', '{img}', '{exp}')".format(
                klass=sql_escape(klass),
                level=sql_escape(level),
                q=sql_escape(row["question"]),
                a=sql_escape(answer),
                img=sql_escape(image),
                exp=sql_escape(row["explanation"]),
            )
        )

    DATA.mkdir(exist_ok=True)
    TASKS.mkdir(parents=True, exist_ok=True)
    fieldnames = [
        "subject",
        "class_name",
        "level",
        "question",
        "answer",
        "image",
        "explanation_of_the_answer",
    ]
    with (DATA / csv_name).open("w", encoding="utf-8", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(csv_rows)

    sql = (
        f"-- Арифметика, {klass}, {level}, {len(rows)} задач.\n"
        "INSERT INTO arithmetic_tasks (subject, class_name, level, question, answer, image, explanation_of_the_answer)\n"
        "VALUES\n"
        + ",\n".join(sql_values)
        + ";\n"
    )
    (DATA / sql_name).write_text(sql, encoding="utf-8")
    print(csv_name, len(rows))


def main() -> None:
    TASKS.mkdir(parents=True, exist_ok=True)
    for (klass, level), builder in BUILDERS.items():
        write_pack(klass, level, builder())


if __name__ == "__main__":
    main()
