def wrap_text(text: str, max_chars: int) -> list[str]:
    words = text.split()
    lines: list[str] = []
    current = ""
    for word in words:
        nxt = f"{current} {word}".strip()
        if len(nxt) > max_chars and current:
            lines.append(current)
            current = word
        else:
            current = nxt
    if current:
        lines.append(current)
    return lines[:5]


def escape_xml(text: str) -> str:
    return (
        str(text)
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )


def formula_from_question(question: str) -> str:
    if ":" in question:
        tail = question.split(":", 1)[1].strip()
        if tail and len(tail) < 90:
            return tail
    for prefix in ("Найдите значение выражения ", "Найдите значение ", "Вычислите "):
        if question.startswith(prefix):
            return question[len(prefix) :]
    return question


