import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIELDS = ["subject", "class_name", "level", "question", "answer", "image", "explanation_of_the_answer"]


def write_csv(filename, level, tasks):
    path = ROOT / "data" / filename
    with path.open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS)
        w.writeheader()
        for i, (question, answer, explanation) in enumerate(tasks, 1):
            w.writerow({
                "subject": "algebra",
                "class_name": "7 класс",
                "level": level,
                "question": question,
                "answer": answer,
                "image": "",
                "explanation_of_the_answer": explanation,
            })
    print(level, len(tasks), path)


